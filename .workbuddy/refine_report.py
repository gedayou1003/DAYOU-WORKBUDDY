# ---------- 第一块转换 ----------
def clean_point(p):
    c = p
    c = re.sub(r'（附件[^（）]*）', '', c)                                        # （附件 PDF 6.2MB）
    c = re.sub(r'附件：[^；；]*?(?:\.html|PDF|docx|MP3|xlsx)[^；；]*[；；]?', '', c)  # 附件：xxx.html...
    c = re.sub(r'中英 PDF \+ 英 PDF\s*', '', c)                                # 中英 PDF + 英 PDF
    c = c.replace('**', '').replace('*', '')
    c = re.sub(r'\s{2,}', ' ', c)
    return c.strip()

def format_post(time, title, points):
    long = len(points) > 5 or any(p.startswith('**图') for p in points)
    if long:
        r = [f'- **[{time}] {title}**']
        for p in points:
            c = clean_point(p)
            if re.match(r'^\d+\.', c):
                r.append(f'    {c}')
            else:
                r.append(f'  - {c}')
        return '\n'.join(r)
    joined = '；'.join(clean_point(p) for p in points).strip('；')
    return f'- **[{time}] {title}** —— {joined}' if joined else f'- **[{time}] {title}**'

def convert_block1(text):
    lines = text.split('\n')
    out = []
    current_group = None
    posts = []
    cur = None
    title_re = re.compile(r'^\*\*(.+?)\s+\[(\d{4}-\d{2}-\d{2})\s+(\d{2}:\d{2})\]\s*·\s*(.+?)\*\*')

    def flush_post():
        nonlocal cur
        if cur is not None:
            posts.append(cur); cur = None

    def flush_group():
        nonlocal current_group, posts
        if current_group is not None:
            out.append(f'**{current_group}**：')
            for t, ti, pts in posts:
                out.append(format_post(t, ti, pts))
            out.append('')
            current_group = None; posts = []

    for line in lines:
        s = line.strip()
        if s.startswith('### ') or s.startswith('## ') or s.startswith('> '):
            flush_post(); flush_group()
            if s.startswith('> '):
                s = s.replace('分板块逐条列出（标题+时间+核心要点，含图片正文）',
                              '分板块按星球归组（时间倒序罗列，含图片正文）')
            out.append(s); out.append(''); continue
        m = title_re.match(s)
        if m:
            flush_post()
            g = m.group(1); t = m.group(3); ti = m.group(4)
            if g != current_group:
                flush_group(); current_group = g
            cur = [t, ti, []]; continue
        if cur is not None:
            if s == '':
                continue
            pt = re.sub(r'^-\s+', '', s)
            cur[2].append(pt); continue
        flush_post(); flush_group()
        if s:
            s = re.sub(r'\s*PDF\s+[\d.]+\s*(?:KB|MB)', '', s)
            s = re.sub(r'（[^（）]*(?:imgs|附件|已读)[^（）]*）', '', s)
            out.append(s)
    flush_post(); flush_group()
    return '\n'.join(out)

